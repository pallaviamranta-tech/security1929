/**
 * Converts the old members-data.json database into SQL for Cloudflare D1.
 *
 * Usage (run from the project folder):
 *   node scripts/json-to-sql.mjs members-data.json import.sql
 *
 * Then import it ONCE with:
 *   npx wrangler d1 execute security-bot-18n28-db --remote --file=import.sql
 *
 * Notes:
 * - The main owner is not imported; it comes from the MAIN_OWNER_ID secret.
 * - Unused legacy keys (banned, maintenance, locks, stickerLocks, contentLocks, files, stickers) are skipped.
 * - The old protection name "pdf" is mapped to "document".
 */
import { readFileSync, writeFileSync } from "node:fs";

const [inputPath = "members-data.json", outputPath = "import.sql"] = process.argv.slice(2);

const PROTECTION_TYPES = new Set(["sticker", "document", "video", "link", "media", "all"]);
const KNOWN_SETTINGS = new Set(["welcome", "antilink", "antiflood", "rules"]);
const stats = {};

const isObj = v => v !== null && typeof v === "object" && !Array.isArray(v);

function count(name) {
  stats[name] = (stats[name] || 0) + 1;
}

/** SQL literal for a string, number, boolean or null. */
function lit(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "boolean") return value ? "1" : "0";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) return "NULL";
    return String(Math.trunc(value));
  }
  return `'${String(value).replace(/'/g, "''")}'`;
}

function intOrNull(v) {
  const n = Number(v);
  return v !== null && v !== undefined && v !== "" && Number.isSafeInteger(n) ? n : null;
}

let source;
try {
  source = JSON.parse(readFileSync(inputPath, "utf8"));
} catch (err) {
  console.error(`Could not read ${inputPath}: ${err.message}`);
  process.exit(1);
}
if (!isObj(source)) {
  console.error("The JSON root must be an object.");
  process.exit(1);
}

const out = ["-- Generated by scripts/json-to-sql.mjs. Import this file only once."];
const emit = sql => out.push(sql);

const groups = isObj(source.groups) ? source.groups : {};
const legacy = key => (isObj(source[key]) ? source[key] : {}); // very old layout: per-group maps at top level

for (const [key, g0] of Object.entries(groups)) {
  const chatId = intOrNull(key);
  if (chatId === null) continue;

  const g = isObj(g0) ? g0 : {};
  const settings = { ...(isObj(g.settings) ? g.settings : {}), ...(isObj(legacy("settings")[key]) ? legacy("settings")[key] : {}) };
  const rules = typeof g.rules === "string" ? g.rules : (typeof settings.rules === "string" ? settings.rules : "");
  const extra = Object.fromEntries(Object.entries(settings).filter(([k]) => !KNOWN_SETTINGS.has(k)));

  emit(
    `INSERT OR IGNORE INTO chat_groups (chat_id, title, added_by, rules, welcome, antilink, antiflood, extra_settings) VALUES (` +
    [
      lit(chatId), lit(g.title || "Group"), lit(intOrNull(g.addedBy)), lit(rules),
      lit(settings.welcome ?? true), lit(settings.antilink ?? false), lit(settings.antiflood ?? false),
      lit(JSON.stringify(extra))
    ].join(", ") + ");"
  );
  count("groups");

  const protection = { ...(isObj(g.protection) ? g.protection : {}), ...(isObj(legacy("protection")[key]) ? legacy("protection")[key] : {}) };
  for (const [rawType, value] of Object.entries(protection)) {
    const type = rawType === "pdf" ? "document" : rawType;
    const until = typeof value === "number" ? value : Number(value?.until);
    if (!PROTECTION_TYPES.has(type) || !Number.isFinite(until)) continue;

    emit(
      `INSERT OR IGNORE INTO group_protections (chat_id, type, until_ms, set_by) VALUES (` +
      [lit(chatId), lit(type), lit(until), lit(intOrNull(value?.by))].join(", ") + ");"
    );
    count("protections");
  }

  const warnings = { ...(isObj(g.warnings) ? g.warnings : {}), ...(isObj(legacy("warnings")[key]) ? legacy("warnings")[key] : {}) };
  for (const [userId, n] of Object.entries(warnings)) {
    const uid = intOrNull(userId);
    const total = Number(n);
    if (uid === null || !Number.isFinite(total) || total < 1) continue;

    emit(
      `INSERT OR IGNORE INTO warnings (chat_id, user_id, count) VALUES (${lit(chatId)}, ${lit(uid)}, ${lit(total)});`
    );
    count("warnings");
  }

  const history = Array.isArray(g.joinHistory) ? g.joinHistory
    : (Array.isArray(legacy("joinHistory")[key]) ? legacy("joinHistory")[key] : []);
  for (const j of history) {
    if (!isObj(j) || intOrNull(j.id) === null) continue;

    emit(
      `INSERT INTO join_history (chat_id, user_id, name, username, joined_at, added_by) VALUES (` +
      [
        lit(chatId), lit(intOrNull(j.id)), lit(j.name || String(j.id)), lit(j.username || null),
        lit(j.joinedAt || new Date(0).toISOString()), lit(intOrNull(j.addedBy))
      ].join(", ") + ");"
    );
    count("join_history");
  }

  const delegated = Array.isArray(g.delegatedOwners) ? g.delegatedOwners
    : (Array.isArray(legacy("delegatedOwners")[key]) ? legacy("delegatedOwners")[key] : []);
  for (const owner of delegated) {
    const uid = intOrNull(owner);
    if (uid === null) continue;

    emit(`INSERT OR IGNORE INTO delegated_owners (chat_id, user_id) VALUES (${lit(chatId)}, ${lit(uid)});`);
    count("delegated_owners");
  }
}

for (const owner of Array.isArray(source.globalOwners) ? source.globalOwners : []) {
  const uid = intOrNull(owner);
  if (uid === null || String(uid) === String(source.mainOwnerId)) continue;

  emit(`INSERT OR IGNORE INTO global_owners (user_id) VALUES (${lit(uid)});`);
  count("global_owners");
}

for (const [key, u] of Object.entries(isObj(source.users) ? source.users : {})) {
  const uid = intOrNull(u?.id ?? key);
  if (uid === null) continue;

  emit(
    `INSERT OR IGNORE INTO users (user_id, name, username, last_seen_at) VALUES (` +
    [lit(uid), lit(u?.name || String(uid)), lit(u?.username || null), lit(u?.lastSeenAt || new Date(0).toISOString())].join(", ") + ");"
  );
  count("users");
}

for (const [chatKey, members] of Object.entries(isObj(source.members) ? source.members : {})) {
  const chatId = intOrNull(chatKey);
  if (chatId === null || !isObj(members)) continue;

  for (const [userKey, m] of Object.entries(members)) {
    const uid = intOrNull(m?.id ?? userKey);
    if (uid === null) continue;

    emit(
      `INSERT OR IGNORE INTO members (chat_id, user_id, name, username) VALUES (` +
      [lit(chatId), lit(uid), lit(m?.name || String(uid)), lit(m?.username || null)].join(", ") + ");"
    );
    count("members");
  }
}

for (const r of Array.isArray(source.reports) ? source.reports : []) {
  if (!isObj(r)) continue;

  emit(
    `INSERT INTO reports (chat_id, group_title, reporter_id, target_id, message_id, created_at) VALUES (` +
    [
      lit(intOrNull(r.chatId) ?? 0), lit(r.groupTitle || null), lit(intOrNull(r.reporterId) ?? 0),
      lit(intOrNull(r.targetId) ?? 0), lit(intOrNull(r.messageId) ?? 0), lit(r.timestamp || new Date(0).toISOString())
    ].join(", ") + ");"
  );
  count("reports");
}

// Audit logs exist in two shapes: the current one and an older {time, type, details} one.
for (const a of Array.isArray(source.auditLogs) ? source.auditLogs : []) {
  if (!isObj(a)) continue;

  let row;
  if (typeof a.action === "string") {
    row = {
      chatId: intOrNull(a.chatId), actorId: intOrNull(a.actorId), targetId: intOrNull(a.targetId),
      action: a.action, extra: a.extra ?? {}, at: a.timestamp
    };
  } else if (typeof a.type === "string") {
    const d = isObj(a.details) ? a.details : {};
    row = {
      chatId: intOrNull(d.groupId), actorId: intOrNull(d.changedBy), targetId: null,
      action: a.type, extra: d, at: a.time
    };
  } else {
    continue;
  }

  emit(
    `INSERT INTO audit_logs (chat_id, actor_id, target_id, action, extra, created_at) VALUES (` +
    [
      lit(row.chatId), lit(row.actorId), lit(row.targetId), lit(row.action),
      lit(JSON.stringify(row.extra)), lit(row.at || new Date(0).toISOString())
    ].join(", ") + ");"
  );
  count("audit_logs");
}

writeFileSync(outputPath, out.join("\n") + "\n", "utf8");

console.log(`Wrote ${outputPath} (${out.length - 1} statements).`);
for (const [name, n] of Object.entries(stats)) console.log(`  ${name}: ${n}`);
